// Newest first for the blog index.
export function getAllPosts(): BlogPost[] {
  return [...blogPosts].sort((a, b) =>
    a.publishedAt < b.publishedAt ? 1 : a.publishedAt > b.publishedAt ? -1 : 0,
  );
}

export function getPost(slug: string): BlogPost | undefined {
  return blogPosts.find((post) => post.slug === slug);
}

export function blogHref(post: BlogPost | string): string {
  const slug = typeof post === 'string' ? post : post.slug;
  return `/blog/${slug}/`;
}

export function blogIndexHref(): string {
  return '/blog/';
}

// Resolve relatedSlugs to posts that still exist in blogPosts.
export function relatedPosts(post: BlogPost): BlogPost[] {
  return post.relatedSlugs
    .map((slug) => getPost(slug))
    .filter((item): item is BlogPost => Boolean(item));
}

// Resolve landingSlugs to SEO landings from lib/landing-pages.
export function linkedLandings(post: BlogPost): LandingPage[] {
  return post.landingSlugs
    .map((slug) => landingPages.find((page) => page.slug === slug))
    .filter((item): item is LandingPage => Boolean(item));
}

// Midday local parse avoids UTC date-shift for YYYY-MM-DD strings.
export function formatBlogDate(isoDate: string): string {
  const date = new Date(`${isoDate}T12:00:00`);
  return new Intl.DateTimeFormat('ru-RU', {
    day: 'numeric',
    month: 'long',
    year: 'numeric',
  }).format(date);
}
